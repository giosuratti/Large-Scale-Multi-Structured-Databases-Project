import pandas as pd
import numpy as np
from neo4j import GraphDatabase

# ===============================
# LETTURA CSV
# ===============================
df = pd.read_csv("disease_symptom_dataset.csv")

# Normalizzazione nomi colonne
df.columns = [c.strip().title() for c in df.columns]

# Rinominare la prima colonna in Disease
df = df.rename(columns={df.columns[0]: "Disease"})
df["Disease"] = df["Disease"].str.strip().str.title()

# ===============================
# CONVERSIONE DEL FORMATO WIDE → LONG
# ===============================
symptom_cols = [col for col in df.columns if col != "Disease"]

long_df = df.melt(
    id_vars="Disease",
    value_vars=symptom_cols,
    var_name="Symptom_list",
    value_name="Present"
)

# Mantieni solo i sintomi presenti (valore 1)
long_df = long_df[long_df["Present"] == 1].drop(columns=["Present"])
long_df["Symptom_list"] = long_df["Symptom_list"].str.strip().str.title()

# ===============================
# CALCOLO PESI TF-IDF
# ===============================
num_diseases = long_df['Disease'].nunique()
total_rows_per_disease = long_df.groupby('Disease').size().to_dict()
rows_per_symptom_disease = long_df.groupby(['Disease','Symptom_list']).size().to_dict()
diseases_per_symptom = long_df.groupby('Symptom_list')['Disease'].nunique().to_dict()

def compute_weight(disease, symptom):
    tf = rows_per_symptom_disease[(disease, symptom)] / total_rows_per_disease[disease]
    idf = np.log((1 + num_diseases) / (1 + diseases_per_symptom[symptom]))
    prior = np.log(1 + total_rows_per_disease[disease])
    return tf * idf * prior



long_df['weight'] = long_df.apply(
    lambda row: compute_weight(row['Disease'], row['Symptom_list']),
    axis=1
)

